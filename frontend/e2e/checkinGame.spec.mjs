import {test,expect} from '@playwright/test';

test('Crew Check-In completes four mission checkpoints, stamps and private history',async ({page})=>{
  await page.goto('/');
  await page.getByRole('navigation',{name:'Primary navigation'}).getByRole('button',{name:/Health Routine/}).click();
  await page.getByRole('navigation',{name:'Choose Health Routine game'}).getByRole('button',{name:/Crew Check-In/}).click();
  await expect(page.getByRole('heading',{name:/DAILY HEALTH LOG/})).toBeVisible();
  await expect(page.getByRole('navigation',{name:'Crew Check-In checkpoints'}).getByRole('button',{name:/Sleep & recovery/})).toBeVisible();
  await page.getByRole('slider',{name:'Hours of sleep'}).fill('6.5');
  await page.getByRole('button',{name:/Save checkpoint/}).click();
  await expect(page.getByRole('button',{name:/Fatigue, mood & workload/})).toHaveAttribute('aria-current','step');
  await page.getByRole('button',{name:'Stressed'}).click();
  await page.getByRole('button',{name:/Save checkpoint/}).click();
  await expect(page.getByRole('button',{name:/Discomfort map/})).toHaveAttribute('aria-current','step');
  await page.getByRole('button',{name:'Select Head / neck'}).click();
  await page.getByRole('combobox',{name:'Head / neck discomfort level'}).selectOption('2');
  await page.getByRole('button',{name:/Save checkpoint/}).click();
  await expect(page.getByRole('button',{name:/Manual readings/})).toHaveAttribute('aria-current','step');
  await expect(page.getByRole('spinbutton',{name:'Heart rate'})).toHaveValue('');
  await page.getByRole('button',{name:/Prefer not to answer/}).click();
  await expect(page.getByText(/Daily mission complete/)).toBeVisible();
  await expect(page.getByText(/60 lifetime XP/)).toBeVisible();
  await expect(page.getByText(/1 skipped today/)).toBeVisible();
  await expect(page.getByText(/6.5h/)).toBeVisible();
  await page.getByRole('button',{name:'Play as Marcus Reed'}).click();
  await expect(page.getByText(/0 lifetime XP/)).toBeVisible();
  await page.getByRole('button',{name:'Play as Elena Park'}).click();
  await expect(page.getByText(/60 lifetime XP/)).toBeVisible();
  await page.reload();
  await page.getByRole('navigation',{name:'Primary navigation'}).getByRole('button',{name:/Health Routine/}).click();
  await page.getByRole('navigation',{name:'Choose Health Routine game'}).getByRole('button',{name:/Crew Check-In/}).click();
  await expect(page.getByText(/60 lifetime XP/)).toBeVisible();
  await page.getByRole('navigation',{name:'Crew Check-In checkpoints'}).getByRole('button',{name:/YOUR MISSION RECORDS/}).click();
  await expect(page.getByText(/6.5h/)).toBeVisible();
});
test('Crew Check-In can skip all sensitive questions for full stamps and delete only one crew day',async ({page})=>{
  await page.goto('/');
  await page.getByRole('navigation',{name:'Primary navigation'}).getByRole('button',{name:/Health Routine/}).click();
  await page.getByRole('navigation',{name:'Choose Health Routine game'}).getByRole('button',{name:/Crew Check-In/}).click();
  for(let n=0;n<4;n++)await page.getByRole('button',{name:/Prefer not to answer/}).click();
  await expect(page.getByText(/4 skipped today/)).toBeVisible();
  await expect(page.getByText(/60 lifetime XP/)).toBeVisible();
  await page.getByRole('button',{name:/Clear today's entries/}).click();
  await page.getByRole('button',{name:'Cancel'}).click();
  await expect(page.getByText(/60 lifetime XP/)).toBeVisible();
  await page.getByRole('button',{name:/Clear today's entries/}).click();
  await page.getByRole('button',{name:/Yes, clear today/}).click();
  await expect(page.getByText(/0 lifetime XP/)).toBeVisible();
  await page.getByRole('navigation',{name:'Choose Health Routine game'}).getByRole('button',{name:/Knowledge Quest/}).click();
  await expect(page.getByRole('region',{name:'Mission game statistics'})).toBeVisible();
  await page.getByRole('navigation',{name:'Choose Health Routine game'}).getByRole('button',{name:/Wellness Expedition/}).click();
  await expect(page.getByRole('heading',{name:/TRAIN YOUR CREW/})).toBeVisible();
});
